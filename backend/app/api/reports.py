@router.get("/student-gaps")
def get_student_learning_gaps_report(
    batch_id: Optional[int] = None,
    format: Optional[str] = "json",
    current_user: User = Depends(require_all_authenticated),
    db: Session = Depends(get_db)
):
    experiments = db.query(Experiment).all()
    timestamp = datetime.datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")

    gap_data = []
    for exp in experiments:
        gap = calculate_student_learning_gap(db, exp.id, batch_id)
        gap_data.append(gap)

    if format.lower() == "csv":
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(["LABGAP - STUDENT PRACTICAL LEARNING GAP AUDIT REPORT"])
        writer.writerow([f"Generated At: {timestamp}", f"Generated By: {current_user.email}"])
        writer.writerow([])
        writer.writerow([
            "Experiment Code", "Experiment Name", "Total Assigned", "Participated",
            "Partially Completed", "Verified Completed", "Unverified Learning Gap", "Gap %"
        ])
        for g in gap_data:
            writer.writerow([
                g.get("experiment_code", "N/A"), g.get("experiment_name", "N/A"),
                g.get("total_assigned", 0), g.get("participated", 0),
                g.get("partially_completed", 0), g.get("verified_completed", 0),
                g.get("unverified_learning_gap", 0), f"{g.get('gap_percentage', 0.0)}%"
            ])
        return PlainTextResponse(
            output.getvalue(),
            media_type="text/csv",
            headers={"Content-Disposition": "attachment; filename=labgap_student_gaps_report.csv"}
        )

    return {
        "report_title": "Student Practical Competency Gap Audit",
        "generated_at": timestamp,
        "generated_by": current_user.email,
        "data": gap_data
    }
