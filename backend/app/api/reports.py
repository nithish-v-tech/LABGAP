import io
import csv
import datetime
from typing import Optional
from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import PlainTextResponse
from sqlalchemy.orm import Session
from app.database.connection import get_db
from app.database.models import (
    Experiment, Equipment, StudentBatch, Student, Laboratory, Schedule,
    CompletionRecord, AnalysisResult, User
)
from app.security.permissions import require_all_authenticated
from app.algorithms.capacity_engine import calculate_experiment_capacity
from app.algorithms.gap_analyzer import calculate_student_learning_gap
from app.algorithms.repair_engine import evaluate_equipment_repairs

router = APIRouter(prefix="/reports", tags=["Reports"])

@router.get("/coverage")
def get_coverage_report(
    format: Optional[str] = "json",
    current_user: User = Depends(require_all_authenticated),
    db: Session = Depends(get_db)
):
    experiments = db.query(Experiment).all()
    default_batch = db.query(StudentBatch).first()
    timestamp = datetime.datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")

    report_rows = []
    for exp in experiments:
        cap = calculate_experiment_capacity(db, exp, default_batch)
        gap = calculate_student_learning_gap(db, exp.id)

        report_rows.append({
            "experiment_code": exp.experiment_code,
            "experiment_name": exp.name,
            "laboratory": exp.laboratory.name if exp.laboratory else "N/A",
            "practical_competency": exp.practical_competency,
            "classification": cap["classification"],
            "active_stations": cap["active_stations"],
            "safe_capacity_per_session": cap["safe_capacity_per_session"],
            "total_assigned_students": gap["total_assigned"],
            "verified_completed": gap["verified_completed"],
            "remaining_learning_gap": gap["unverified_learning_gap"],
            "equipment_shortage": cap["equipment_shortage"],
            "explanation": cap["reason"]
        })

    if format.lower() == "csv":
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(["LABGAP - EXPERIMENT PRACTICAL LEARNING COVERAGE REPORT"])
        writer.writerow([f"Generated At: {timestamp}", f"Generated By: {current_user.email}"])
        writer.writerow([])
        writer.writerow([
            "Experiment Code", "Experiment Name", "Laboratory", "Practical Competency",
            "Coverage Classification", "Active Stations", "Safe Capacity/Session",
            "Assigned Students", "Verified Competent", "Remaining Learning Gap",
            "Equipment Shortage", "Algorithmic Explanation"
        ])
        for r in report_rows:
            writer.writerow([
                r["experiment_code"], r["experiment_name"], r["laboratory"], r["practical_competency"],
                r["classification"], r["active_stations"], r["safe_capacity_per_session"],
                r["total_assigned_students"], r["verified_completed"], r["remaining_learning_gap"],
                r["equipment_shortage"], r["explanation"]
            ])
        return PlainTextResponse(
            output.getvalue(),
            media_type="text/csv",
            headers={"Content-Disposition": "attachment; filename=labgap_coverage_report.csv"}
        )

    return {
        "report_title": "Practical Learning Coverage & Capacity Analysis Report",
        "generated_at": timestamp,
        "generated_by": current_user.email,
        "total_experiments": len(report_rows),
        "data": report_rows
    }

